/**
 * API response types. All money fields are integer cents (JSON numbers, always
 * safe integers). All quantities are integer shares. Timestamps are ISO-8601.
 */

export type Role = 'USER' | 'ADMIN';
export type SecurityStatus = 'ACTIVE' | 'HALTED' | 'SUSPENDED' | 'UNLISTED';
export type OrderSide = 'BUY' | 'SELL';
export type OrderType = 'MARKET' | 'LIMIT';
export type OrderStatus = 'OPEN' | 'PARTIALLY_FILLED' | 'FILLED' | 'CANCELLED' | 'REJECTED';
export type ReferencePriceKind = 'VERIFIED' | 'SIMULATED';
export type DisplayPriceKind = 'LAST_TRADE' | 'REFERENCE_VERIFIED' | 'REFERENCE_SIMULATED';

export interface ApiError {
  error: { code: string; message: string; details?: unknown };
}

export interface MeResponse {
  user: { id: string; username: string; role: Role; createdAt: string };
}

export interface SecurityView {
  ticker: string;
  name: string;
  originalRank: number;
  /** null = status not yet verified (treated as non-tradable). */
  listingStatus: SecurityStatus | null;
  tradable: boolean;
  /** Why trading is blocked, if it is. */
  tradingBlockReason: string | null;
  symbolHalted: boolean;
  referencePriceCents: number | null;
  referencePriceKind: ReferencePriceKind | null;
  lastPriceCents: number | null;
  lastTradeAt: string | null;
  /** lastPriceCents if the security has traded, else the reference price. */
  displayPriceCents: number | null;
  displayPriceKind: DisplayPriceKind | null;
  changeFromReferenceBps: number | null;
  bestBidCents: number | null;
  bestAskCents: number | null;
  volume24h: number;
  /** Executions in the last 24h. */
  trades24h: number;
  /** Price 24h ago: the last trade at or before then, else the reference price. */
  price24hAgoCents: number | null;
  /** displayPrice minus price24hAgo; null when either is unknown. */
  change24hCents: number | null;
  change24hBps: number | null;
  /** Shares issued in the current epoch (market maker inventory issuance). */
  sharesOutstanding: number;
  description: string;
  imageUrl: string | null;
}

export interface SecurityDetailView extends SecurityView {
  news: string | null;
  background: string | null;
  tradingRestriction: string | null;
  bookVersion: number;
  historicalNotes: { changeBps: number | null; note: string | null; kind: string }[];
  /** Fictional, parody business profile (always label as fictional in the UI). */
  profile: { sector: string; tagline: string; profile: string };
  /** The brother's entry in the Active Rankings document (reference content, not market data). */
  activity: { rank: number; of: number; title: string; emailCount: number; writeup: string; source: string } | null;
  /** True when this security's opening trades were generated by the simulation desk. */
  simulatedHistory: boolean;
}

export interface BookLevel {
  priceCents: number;
  quantity: number;
  orders: number;
}

export interface OrderBookView {
  ticker: string;
  bookVersion: number;
  bestBidCents: number | null;
  bestAskCents: number | null;
  spreadCents: number | null;
  bids: BookLevel[];
  asks: BookLevel[];
}

export interface TradeView {
  id: number;
  ticker: string;
  priceCents: number;
  quantity: number;
  aggressorSide: OrderSide;
  executedAt: string;
}

export interface MyTradeView extends TradeView {
  side: OrderSide;
  orderId: string;
  liquidity: 'MAKER' | 'TAKER';
  notionalCents: number;
}

export interface OrderView {
  id: string;
  seq: number;
  ticker: string;
  side: OrderSide;
  type: OrderType;
  status: OrderStatus;
  quantity: number;
  filledQuantity: number;
  remainingQuantity: number;
  limitPriceCents: number | null;
  maxSpendCents: number | null;
  reservedCents: number;
  reservedQuantity: number;
  /** Cash paid (buys) or received (sells) so far. */
  filledNotionalCents: number;
  averageFillPriceCents: number | null;
  rejectReason: string | null;
  cancelReason: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface FillView {
  tradeId: number;
  priceCents: number;
  quantity: number;
  counterpartyOrderId: string;
}

export interface PlaceOrderResponse {
  order: OrderView;
  fills: FillView[];
  /** true when this response is a replay of an earlier request with the same Idempotency-Key. */
  replayed: boolean;
}

